def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help=f"Dataset destination (default: {DEFAULT_OUTPUT})",
    )
    parser.add_argument(
        "--metadata-output",
        type=Path,
        default=DEFAULT_METADATA_OUTPUT,
        help=f"Metadata destination (default: {DEFAULT_METADATA_OUTPUT})",
    )
    parser.add_argument(
        "--source-pdf",
        type=Path,
        help="Optional local source PDF whose pinned SHA-256 must match.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify that existing outputs exactly match a fresh build.",
    )
    return parser.parse_args()


def check_or_write(path: Path, expected: bytes, check: bool) -> None:
    if check:
        if not path.is_file():
            raise SystemExit(f"Missing output for --check: {path}")
        actual = path.read_bytes()
        if actual != expected:
            raise SystemExit(f"Output is stale or differs from the builder: {path}")
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(expected)


def main() -> None:
    args = parse_args()
    if args.source_pdf:
        source_pdf = args.source_pdf.expanduser().resolve()
        if not source_pdf.is_file():
            raise SystemExit(f"Source PDF does not exist: {source_pdf}")
        digest = sha256_path(source_pdf)
        if digest != SOURCE["pdf_sha256"]:
            raise SystemExit(
                "Source PDF SHA-256 mismatch: "
                f"expected {SOURCE['pdf_sha256']}, got {digest}"
            )

    dataset = make_dataset()
    dataset_bytes = json_bytes(dataset)
    metadata = make_metadata(dataset_bytes, dataset)
    metadata_bytes = json_bytes(metadata)
    check_or_write(args.output.resolve(), dataset_bytes, args.check)
    check_or_write(args.metadata_output.resolve(), metadata_bytes, args.check)

    verb = "Verified" if args.check else "Wrote"
    print(
        f"{verb} {len(dataset['systems'])} systems, "
        f"{dataset['summary']['total']['rated_transfer_capacity_mw']} MW and "
        f"{dataset['summary']['total']['line_length_km']} km"
    )
    print(f"Dataset SHA-256: {sha256_bytes(dataset_bytes)}")
    print(f"Metadata SHA-256: {sha256_bytes(metadata_bytes)}")


if __name__ == "__main__":
    main()
