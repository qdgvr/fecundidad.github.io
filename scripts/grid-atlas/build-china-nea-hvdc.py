def unit(
    label_zh: str,
    commissioned_on: str | None = None,
    voltage_kv: int | None = None,
    capacity_mw: int | None = None,
    source_note_zh: str | None = None,
) -> dict[str, Any]:
    value: dict[str, Any] = {"label_zh": label_zh}
    if commissioned_on:
        value["commissioned_on"] = commissioned_on
    if voltage_kv is not None:
        value["rated_voltage"] = {
            "notation": f"±{voltage_kv}",
            "magnitude_kv": voltage_kv,
        }
    if capacity_mw is not None:
        value["rated_transfer_capacity_mw"] = capacity_mw
    if source_note_zh:
        value["source_note_zh"] = source_note_zh
    return value


def event(commissioned_on: str, scope_zh: str) -> dict[str, str]:
    return {"commissioned_on": commissioned_on, "scope_zh": scope_zh}


def system(
    sequence: int,
    name_zh: str,
    system_type: str,
    capacity_mw: int,
    length_km: int,
    grid_groups: list[str],
    *,
    voltage_kv: int | None = None,
    units: list[dict[str, Any]] | None = None,
    commissioning_events: list[dict[str, str]] | None = None,
    capacity_basis: str = "reported_system_total",
) -> dict[str, Any]:
    value: dict[str, Any] = {
        "nea_sequence": sequence,
        "system_name_zh": name_zh,
        "system_type": system_type,
        "system_type_zh": SYSTEM_TYPES[system_type],
        "rated_transfer_capacity_mw": capacity_mw,
        "capacity_basis": capacity_basis,
        "line_length_km": length_km,
        "grid_groups": grid_groups,
        "units": units or [],
    }
    if voltage_kv is not None:
        value["rated_voltage"] = {
            "notation": f"±{voltage_kv}",
            "magnitude_kv": voltage_kv,
        }
    if commissioning_events:
        value["commissioning_events"] = commissioning_events
    return value


